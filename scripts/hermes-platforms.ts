/**
 * McBot's list of chat apps, generated from Hermes' own platform plugins
 * (hermes/plugins/platforms/<id>/plugin.yaml: label, requires_env, optional_env), so every
 * variable McBot writes is one Hermes declares (hard rule 2). `npm test` fails when the generated
 * file is stale: run `npm run engine:platforms` after a Hermes sync.
 *
 *   npx tsx scripts/hermes-platforms.ts          write src/contracts/platforms.generated.ts
 *   renderPlatforms()                             the file's text (used by the test)
 */
import { readFileSync, readdirSync, existsSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { parse } from "yaml";

const ROOT = join(import.meta.dirname ?? __dirname, "..");
const DIR = join(ROOT, "hermes/plugins/platforms");
export const OUT = join(ROOT, "src/contracts/platforms.generated.ts");

interface Env { name: string; description?: string; prompt?: string; url?: string; password?: boolean }

export function renderPlatforms(): string {
  const rows: string[] = [];
  for (const id of readdirSync(DIR).sort()) {
    const file = join(DIR, id, "plugin.yaml");
    if (!existsSync(file)) continue;
    const p = parse(readFileSync(file, "utf8")) as { label?: string; requires_env?: Env[]; optional_env?: Env[] };
    const required = (p.requires_env ?? []).filter((e) => e && typeof e.name === "string");
    // A chat app the board can set up has something to fill in (a2a, for one, is configured elsewhere).
    if (!required.length) continue;
    const allowed = (p.optional_env ?? []).find((e) => /_ALLOWED_USERS$/.test(e.name) && !/GROUP/.test(e.name))?.name ?? null;
    const fields = required.map((e) => {
      const prompt = (e.prompt ?? e.description ?? e.name).replace(/\s+/g, " ").trim();
      return `      { env: ${JSON.stringify(e.name)}, secret: ${e.password === true}, prompt: ${JSON.stringify(prompt)}${e.url ? `, url: ${JSON.stringify(e.url)}` : ""} },`;
    });
    rows.push(
      `  ${JSON.stringify(id)}: {`,
      `    label: ${JSON.stringify(p.label ?? id)},`,
      `    required: [`,
      ...fields,
      `    ],`,
      `    allowedUsersEnv: ${JSON.stringify(allowed)},`,
      `  },`,
    );
  }
  return [
    "// Generated by scripts/hermes-platforms.ts from hermes/plugins/platforms/*/plugin.yaml. Do not edit.",
    "// Run `npm run engine:platforms` after a Hermes sync; `npm test` fails while this file is stale.",
    "",
    "export interface PlatformField {",
    "  /** The variable Hermes reads, in the agent's .env. */",
    "  env: string;",
    "  /** A password or token (saved in McBot, never on the board) or a plain setting (on the board). */",
    "  secret: boolean;",
    "  prompt: string;",
    "  url?: string;",
    "}",
    "",
    "export interface Platform {",
    "  label: string;",
    "  required: readonly PlatformField[];",
    "  /** Who may message the bot (comma-separated ids); null when the app has no such list. */",
    "  allowedUsersEnv: string | null;",
    "}",
    "",
    "export const PLATFORMS = {",
    ...rows,
    "} as const satisfies Record<string, Platform>;",
    "",
    "export type PlatformId = keyof typeof PLATFORMS;",
    "",
  ].join("\n");
}

if (process.argv[1] && /hermes-platforms\.ts$/.test(process.argv[1])) {
  writeFileSync(OUT, renderPlatforms());
  console.log(`wrote ${OUT}`);
}
