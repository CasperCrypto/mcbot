/**
 * The website draws the same glass food bots as the app. site/ has no build step,
 * so this writes them there once: site/foods.js (src/app/faces/foods.ts as a
 * browser script, `window.McBotFoods`) and site/foods.css (the --food-* tokens and
 * styles/faces.css). It also writes the logo as standalone SVG files:
 * site/assets/logo.svg (favicon) and design/icon.svg (the app icon's source;
 * design/icon-1024.png is rendered from it, then `npx tauri icon design/icon-1024.png`).
 * `npm test` fails when any of them is out of date.
 *
 *   npm run site:foods
 */
import { buildSync } from "esbuild";
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { logoSvg } from "../src/app/faces/foods";

const root = join(import.meta.dirname, "..");
const HEAD = "/* Generated by `npm run site:foods` from src/app/faces/foods.ts and src/app/styles/faces.css. Do not edit. */\n";

/** The logo with its styles inside, for places without the app's CSS (favicon, app icon). */
function standalone(css: string, size: number, x = 0, y = 0): string {
  const still = ".food .lids, .food .body { animation: none !important; } .food { filter: none; }";
  return logoSvg(size, "logo", "McBot")
    .replace('<svg class="food"', `<svg xmlns="http://www.w3.org/2000/svg" x="${x}" y="${y}" class="food"`)
    .replace("<defs>", `<style>${css.replace(/\/\*[\s\S]*?\*\//g, "").replace(/\s+/g, " ")} ${still}</style><defs>`);
}

export function siteFoods(): { js: string; css: string; logo: string; icon: string } {
  const out = buildSync({
    entryPoints: [join(root, "src/app/faces/foods.ts")],
    bundle: true,
    write: false,
    format: "iife",
    globalName: "McBotFoods",
    target: "es2020",
    legalComments: "none",
    charset: "utf8",
  });
  const js = HEAD + out.outputFiles[0]!.text.replace(/^\s*\/\/ .*\n/gm, "");
  const tokens = readFileSync(join(root, "src/app/styles/tokens.css"), "utf8")
    .split("\n")
    .filter((l) => /^\s*--(food|logo)-/.test(l))
    .join("\n");
  const faces = readFileSync(join(root, "src/app/styles/faces.css"), "utf8");
  const css = `${HEAD}:root {\n  --ease: cubic-bezier(0.22, 1, 0.36, 1);\n  --ease-spring: cubic-bezier(0.34, 1.45, 0.64, 1);\n  --t-slow: 380ms;\n${tokens}\n}\n${faces}`;
  const logo = standalone(css, 64) + "\n";
  // macOS icon grid: an 824px body on a 1024 canvas.
  const icon =
    `<svg xmlns="http://www.w3.org/2000/svg" width="1024" height="1024" viewBox="0 0 1024 1024">\n` +
    `<defs><linearGradient id="bg" x1="0" y1="0" x2="0" y2="1"><stop offset="0" stop-color="#2e2e33"/><stop offset="1" stop-color="#101012"/></linearGradient>` +
    `<radialGradient id="glow" cx="0.5" cy="0.42" r="0.5"><stop offset="0" stop-color="#ffffff" stop-opacity="0.1"/><stop offset="1" stop-color="#ffffff" stop-opacity="0"/></radialGradient></defs>\n` +
    `<rect x="100" y="100" width="824" height="824" rx="186" fill="url(#bg)"/>\n` +
    `<rect x="100" y="100" width="824" height="824" rx="186" fill="url(#glow)"/>\n` +
    `<rect x="101" y="101" width="822" height="822" rx="185" fill="none" stroke="#ffffff" stroke-opacity="0.08" stroke-width="2"/>\n` +
    standalone(css, 640, 192, 196) +
    `\n</svg>\n`;
  return { js, css, logo, icon };
}

if (process.argv[1] && import.meta.filename === process.argv[1]) {
  const { js, css, logo, icon } = siteFoods();
  writeFileSync(join(root, "site/foods.js"), js);
  writeFileSync(join(root, "site/foods.css"), css);
  writeFileSync(join(root, "site/assets/logo.svg"), logo);
  writeFileSync(join(root, "design/icon.svg"), icon);
  console.log("site/foods.js, site/foods.css, site/assets/logo.svg, design/icon.svg");
}
